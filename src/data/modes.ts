/**
 * The failure-mode table.
 *
 * One row per mode. There is deliberately no component per mode: the 3D scene
 * reads `deformation` and `damage` to decide how to push the specimen around,
 * and the panels read the Arabic prose. Adding a mode means adding a row here.
 *
 * Technical terms stay in English exactly as the standards write them.
 */

import type { Family } from './alloys'

export type ModeFamily = 'mechanical' | 'environmental'

/** How the shader should move the specimen. */
export type Deformation =
  | 'stretch'
  | 'squash'
  | 'bend'
  | 'twist'
  | 'shear'
  | 'cyclic'
  | 'creep'
  | 'impact'
  | 'static'

/** What damage the surface should show. */
export type Damage = 'none' | 'crack' | 'pits' | 'branching' | 'grainBoundary' | 'intergranularCrack'

export interface Driver {
  key: DriverKey
  labelAr: string
  unit: string
  min: number
  max: number
  step: number
  /** Slider is logarithmic; min/max are then log10 of the real value. */
  log?: boolean
}

export type DriverKey =
  | 'drive'
  | 'tempC'
  | 'stressFrac'
  | 'stressAmp'
  | 'cyclesLog'
  | 'timeLogH'
  | 'chlorideLog'
  | 'slenderness'
  | 'hydrogenPpm'

export interface FailureMode {
  id: string
  /** English technical name — never translated. */
  term: string
  nameAr: string
  family: ModeFamily
  deformation: Deformation
  damage: Damage
  /** Short line under the mode name in the rail. */
  taglineAr: string

  primary: Driver
  secondary: Driver[]

  /** What is physically happening, in Arabic. */
  mechanismAr: string
  /** What the broken part looks like when you pick it up — the forensic tell. */
  appearanceAr: string
  /** The warning the operator gets before it lets go, if any. */
  warningAr: string
  /** How it is prevented in design and in service. */
  preventionAr: string
  /** The governing relation, written in English notation. */
  formula: string
  formulaNoteAr: string
  /** How the story changes for another alloy family, when it does. */
  familyNotesAr?: Partial<Record<Family, string>>
}

const DRIVE = (labelAr: string, max = 1): Driver => ({
  key: 'drive', labelAr, unit: '%', min: 0, max, step: 0.005,
})

